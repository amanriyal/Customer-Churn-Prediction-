from sklearn.model_selection import train_test_split
X=df.drop(['Churn','CustomerID'],axis=1)
Y=df['Churn']
X_train, X_test, y_train, y_test = train_test_split(
    X, Y, test_size=0.2, random_state=42
)



X_train

from sklearn.preprocessing import StandardScaler
Scaler=StandardScaler()
X_train_scaled=Scaler.fit_transform(X_train)
X_test_scaled=Scaler.transform(X_test)

X_test_scaled

from sklearn.linear_model import LogisticRegression
logistic=LogisticRegression()
logistic.fit(X_train_scaled,y_train)

prediction=logistic.predict(X_test_scaled)

prediction

from sklearn.metrics import accuracy_score, confusion_matrix , classification_report

accuracy_score(y_test,prediction)

from sklearn.neighbors import KNeighborsClassifier
knn=KNeighborsClassifier(n_neighbors= 5)
knn.fit(X_train_scaled,y_train)

knn_prediction=knn.predict(X_test_scaled)

accuracy_score(y_test,knn_prediction)

confusion_matrix(y_test,knn_prediction)

from sklearn.tree import DecisionTreeClassifier
dt_model=DecisionTreeClassifier(max_depth=5)
dt_model.fit(X_train_scaled,y_train)

dt_pred=dt_model.predict(X_test_scaled)

accuracy_score(y_test,dt_pred)

print("Train Accuracy:", dt_model.score(X_train_scaled, y_train))
print("Test Accuracy:", dt_model.score(X_test_scaled, y_test))